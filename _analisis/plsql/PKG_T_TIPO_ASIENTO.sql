PROCEDURE EDITAR
(
    p_ID_TIPO_ASIENTO IN EJECUCION.T_TIPO_ASIENTO.ID_TIPO_ASIENTO%TYPE DEFAULT NULL,
    p_CODIGO IN EJECUCION.T_TIPO_ASIENTO.CODIGO%TYPE DEFAULT NULL,
    p_DESCRIPCION IN EJECUCION.T_TIPO_ASIENTO.DESCRIPCION%TYPE DEFAULT NULL
,p_MSG IN OUT varchar2
)
IS

V_ID_TIPO_ASIENTO NUMBER(10);
V_CODIGO VARCHAR2(10);
V_DESCRIPCION VARCHAR2(50);

BEGIN
    V_ID_TIPO_ASIENTO := p_ID_TIPO_ASIENTO;
    V_CODIGO := p_CODIGO;
    V_DESCRIPCION := p_DESCRIPCION;

    UPDATE EJECUCION.T_TIPO_ASIENTO SET
        CODIGO = V_CODIGO,
        DESCRIPCION = V_DESCRIPCION
    WHERE
        ID_TIPO_ASIENTO = V_ID_TIPO_ASIENTO
    ;

     exception
       when v_error_00001 then
          p_MSG :='Numero duplicado para esa vigencia.';
          pkg_util.base_rollback;
       when v_error_01407 then
          p_MSG :='No se puede insertar valores nulos.';
          pkg_util.base_rollback;
       when others then
          p_MSG :='Error al EDITAR. Verifique: '|| sqlerrm;
          pkg_util.base_rollback;

END EDITAR;

