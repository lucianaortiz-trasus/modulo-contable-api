PROCEDURE BUSCARPORPK
(
    p_T_TIPO_ASIENTO OUT ty_CURSOR,
    p_ID_TIPO_ASIENTO IN EJECUCION.T_TIPO_ASIENTO.ID_TIPO_ASIENTO%TYPE DEFAULT NULL
)
IS
V_ID_TIPO_ASIENTO NUMBER(10);

BEGIN
     V_ID_TIPO_ASIENTO := p_ID_TIPO_ASIENTO;

    OPEN p_T_TIPO_ASIENTO FOR
    SELECT
        EJECUCION.T_TIPO_ASIENTO.ID_TIPO_ASIENTO,
        EJECUCION.T_TIPO_ASIENTO.CODIGO,
        EJECUCION.T_TIPO_ASIENTO.DESCRIPCION
    FROM EJECUCION.T_TIPO_ASIENTO
    WHERE
        (EJECUCION.T_TIPO_ASIENTO.ID_TIPO_ASIENTO = V_ID_TIPO_ASIENTO)
    ;
END BUSCARPORPK;

PROCEDURE BUSCAR
(
    p_T_TIPO_ASIENTO OUT ty_CURSOR,
    p_ID_TIPO_ASIENTO IN EJECUCION.T_TIPO_ASIENTO.ID_TIPO_ASIENTO%TYPE DEFAULT NULL,
    p_CODIGO IN EJECUCION.T_TIPO_ASIENTO.CODIGO%TYPE DEFAULT NULL,
    p_DESCRIPCION IN EJECUCION.T_TIPO_ASIENTO.DESCRIPCION%TYPE DEFAULT NULL,
    p_PAGINA IN NUMBER DEFAULT NULL,
    p_TAMANOPAGINA IN NUMBER DEFAULT NULL,
    p_CANTIDADDEREGISTROS OUT NUMBER

)
IS

   V_ID_TIPO_ASIENTO NUMBER(10);
   V_CODIGO VARCHAR2(10);
   V_DESCRIPCION VARCHAR2(50);
   V_PAGINA NUMBER(10);
   V_TAMANOPAGINA NUMBER(10);

    v_INICIO NUMBER;
    v_FIN NUMBER;

    v_SELECT varchar2(2000);
    v_SELECT_PAGINA varchar2(2000);
    v_SELECT_COUNT varchar2(2000);

    v_CANTIDAD varchar2(2000);

    v_FROM_COUNT varchar2(1000);

    v_WHERE_PAGINA varchar2(1000);
    v_WHERE_COUNT varchar2(1000);

    v_SUB_CONSULTA VARCHAR2(30000);
    v_BUSCAR VARCHAR2(30000);
    v_AND VARCHAR2(5);
BEGIN
    V_ID_TIPO_ASIENTO := p_ID_TIPO_ASIENTO;
    V_CODIGO := p_CODIGO;
    V_DESCRIPCION := p_DESCRIPCION;
    V_PAGINA := p_PAGINA;
    V_TAMANOPAGINA := p_TAMANOPAGINA;

    BEGIN
        v_SELECT_COUNT := 'SELECT COUNT(*) ';
        v_FROM_COUNT := 'FROM EJECUCION.T_TIPO_ASIENTO ';
        v_WHERE_COUNT := '';
        v_AND := 'WHERE';

        IF V_ID_TIPO_ASIENTO IS NOT NULL THEN
            v_WHERE_COUNT := v_WHERE_COUNT || v_AND || ' EJECUCION.T_TIPO_ASIENTO.ID_TIPO_ASIENTO = ' || V_ID_TIPO_ASIENTO;
            v_AND := ' AND';
        END IF;

        IF V_CODIGO IS NOT NULL THEN
            v_WHERE_COUNT := v_WHERE_COUNT || v_AND || ' EJECUCION.T_TIPO_ASIENTO.CODIGO LIKE ''%' || V_CODIGO || '%''';
            v_AND := ' AND';
        END IF;

        IF V_DESCRIPCION IS NOT NULL THEN
            v_WHERE_COUNT := v_WHERE_COUNT || v_AND || ' EJECUCION.T_TIPO_ASIENTO.DESCRIPCION LIKE ''%' || V_DESCRIPCION || '%''';
        END IF;

        v_CANTIDAD := v_SELECT_COUNT || v_FROM_COUNT || v_WHERE_COUNT;
    END;

    EXECUTE IMMEDIATE v_CANTIDAD INTO p_CANTIDADDEREGISTROS;

    BEGIN
        IF V_PAGINA IS NULL THEN
            v_INICIO := 0;
            v_FIN := p_CANTIDADDEREGISTROS;
        ELSE
            IF V_PAGINA = 1 THEN
                v_INICIO := 0;
                v_FIN := v_INICIO + V_TAMANOPAGINA;
            ELSE
                v_INICIO := (V_PAGINA - 1) * V_TAMANOPAGINA;
                v_FIN := v_INICIO + V_TAMANOPAGINA;
            END IF;
        END IF;
    END;

    BEGIN
        v_SELECT_PAGINA := ' SELECT * FROM (SELECT V.* , ROWNUM  NUMERODEREGISTRO FROM (';
        v_SELECT := 'SELECT ' ||
            'EJECUCION.T_TIPO_ASIENTO.ID_TIPO_ASIENTO, ' ||
            'EJECUCION.T_TIPO_ASIENTO.CODIGO, ' ||
            'EJECUCION.T_TIPO_ASIENTO.DESCRIPCION ';

        v_SUB_CONSULTA := v_SELECT || v_FROM_COUNT || v_WHERE_COUNT || ' ORDER BY 1';--Falta colocar columna de Ordenamiento
        v_WHERE_PAGINA := ' WHERE NUMERODEREGISTRO > ' || v_INICIO || '' || ' AND NUMERODEREGISTRO <= ' || v_FIN || '';

        v_BUSCAR := v_SELECT_PAGINA || v_SUB_CONSULTA || ')V )' || v_WHERE_PAGINA || ' ORDER BY 1' ;--Falta colocar columna de Ordenamiento

    END;

    OPEN p_T_TIPO_ASIENTO FOR v_BUSCAR;
END BUSCAR;

END PKG_T_TIPO_ASIENTO;

